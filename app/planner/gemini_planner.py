import json
import logging
from app.models.agent import ExecutionPlan, ExecutionStep, ExecutionStatus
from app.planner.base import BasePlanner
from app.services.gemini import GeminiService, GeminiAPIError

logger = logging.getLogger(__name__)


class GeminiPlanner(BasePlanner):
    def __init__(self, gemini_service: GeminiService):
        self.gemini_service = gemini_service

    async def create_plan(self, prompt: str) -> ExecutionPlan:
        logger.info(f"Creating execution plan for prompt: {prompt}")

        # Prompt engineering instructing Gemini to output a JSON list of numbered plan steps
        system_instruction = (
            "You are an autonomous AI planning agent. Your goal is to analyze the user request "
            "and create a numbered execution plan. Each step in the plan must represent a single "
            "sequential milestone or action. Return the plan ONLY as a JSON list of strings, "
            "where each string is a numbered step (e.g. \"1. Understand request\").\n\n"
            "Example Output:\n"
            "[\n"
            "  \"1. Understand request\",\n"
            "  \"2. Identify assumptions\",\n"
            "  \"3. Draft proposal\",\n"
            "  \"4. Review proposal\",\n"
            "  \"5. Generate DOCX\"\n"
            "]\n\n"
            "Do not output markdown code blocks (like ```json), introduction, or any explanation."
        )

        try:
            raw_response = await self.gemini_service.generate_content(
                prompt=f"System Instructions:\n{system_instruction}\n\nUser Request: {prompt}",
                response_mime_type="application/json"
            )
            logger.debug(f"Gemini API Response: {raw_response}")

            steps_list = json.loads(raw_response)
            if not isinstance(steps_list, list):
                raise ValueError("Response from Gemini API is not a JSON list")

            steps = []
            for idx, step_desc in enumerate(steps_list, start=1):
                steps.append(
                    ExecutionStep(
                        id=idx,
                        description=str(step_desc),
                        status=ExecutionStatus.PENDING,
                    )
                )
            
            if not steps:
                raise ValueError("Empty plan generated by Gemini")

            return ExecutionPlan(steps=steps)

        except (GeminiAPIError, Exception) as err:
            logger.error(f"Failed to generate plan using Gemini API: {err}. Using fallback.")
            return self._generate_fallback_plan(prompt)

    def _generate_fallback_plan(self, prompt: str) -> ExecutionPlan:
        # Default enterprise-grade fallback plan
        fallback_steps = [
            f"1. Analyze request: {prompt}",
            "2. Identify target audience and layout assumptions",
            "3. Draft initial structured document sections",
            "4. Perform reflection check and verification",
            "5. Compile and generate Word (.docx) document",
        ]
        return ExecutionPlan(
            steps=[
                ExecutionStep(
                    id=idx,
                    description=desc,
                    status=ExecutionStatus.PENDING,
                )
                for idx, desc in enumerate(fallback_steps, start=1)
            ]
        )


